#!/usr/bin/env node
// Writes the two things derived from extension/regions.json: the
// optional_host_permissions list in extension/manifest.json, and the region
// list the options page offers, extension/src/core/regions.js.
//
//   node scripts/gen-manifest.mjs          rewrite both
//   node scripts/gen-manifest.mjs --check  fail if either is out of date
//
// Match patterns cannot put a wildcard in the middle of a host, so the portal
// API host is listed once per region (DESIGN-0001, "Manifest and permissions").

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const MANIFEST = fileURLToPath(
  new URL("../extension/manifest.json", import.meta.url),
);
const REGIONS = fileURLToPath(
  new URL("../extension/regions.json", import.meta.url),
);
const REGIONS_MODULE = fileURLToPath(
  new URL("../extension/src/core/regions.js", import.meta.url),
);

// Hosts that may be requested at enrolment. None are granted at install.
const PORTAL_PAGE_PATTERNS = ["https://*.awsapps.com/*", "https://*.app.aws/*"];
const OKTA_PATTERNS = [
  "https://*.okta.com/*",
  "https://*.oktapreview.com/*",
  "https://*.okta-emea.com/*",
];

/**
 * @param {string[]} regions
 * @returns {string[]}
 */
export function optionalHostPermissions(regions) {
  const api = [...regions]
    .sort()
    .map((region) => `https://portal.sso.${region}.amazonaws.com/*`);
  return [...PORTAL_PAGE_PATTERNS, ...api, ...OKTA_PATTERNS];
}

/**
 * @param {string[]} regions
 * @returns {string} The source of extension/src/core/regions.js.
 */
export function regionsModule(regions) {
  const lines = [...regions].sort().map((region) => `  "${region}",`);
  return [
    "// Generated by scripts/gen-manifest.mjs from extension/regions.json.",
    "// Do not edit by hand.",
    "",
    "/** The AWS regions a portal can be enrolled in. */",
    "export const REGIONS = Object.freeze([",
    ...lines,
    "]);",
    "",
  ].join("\n");
}

/**
 * @param {string} path
 * @returns {Promise<string>} The file's contents, or "" if it does not exist.
 */
async function readOrEmpty(path) {
  try {
    return await readFile(path, "utf8");
  } catch {
    return "";
  }
}

async function main() {
  const check = process.argv.includes("--check");
  const { regions } = JSON.parse(await readFile(REGIONS, "utf8"));
  const manifest = JSON.parse(await readFile(MANIFEST, "utf8"));
  const wantedOrigins = optionalHostPermissions(regions);
  const wantedModule = regionsModule(regions);

  const manifestCurrent =
    JSON.stringify(manifest.optional_host_permissions ?? []) ===
    JSON.stringify(wantedOrigins);
  const moduleCurrent = (await readOrEmpty(REGIONS_MODULE)) === wantedModule;
  if (manifestCurrent && moduleCurrent) {
    console.log("manifest and region list are up to date");
    return;
  }
  if (check) {
    console.error(
      "extension/manifest.json or extension/src/core/regions.js is out of " +
        "date with extension/regions.json.\nRun: node scripts/gen-manifest.mjs",
    );
    process.exitCode = 1;
    return;
  }
  if (!manifestCurrent) {
    manifest.optional_host_permissions = wantedOrigins;
    await writeFile(MANIFEST, `${JSON.stringify(manifest, null, 2)}\n`);
    console.log(`wrote ${wantedOrigins.length} optional host permissions`);
  }
  if (!moduleCurrent) {
    await writeFile(REGIONS_MODULE, wantedModule);
    console.log(`wrote ${regions.length} regions to src/core/regions.js`);
  }
}

// Run only when executed directly, so tests can import the helper above.
if (import.meta.main) {
  await main();
}
